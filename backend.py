def _distribute_minutes(total_minutes: int, num_sections: int = 6) -> list[int]:
    """
    Distributes total_minutes across 6 lesson sections such that
    the sum is strictly equal to total_minutes.
    """
    if total_minutes <= 0:
        return [0] * num_sections
    if total_minutes < num_sections:
        res = [0] * num_sections
        for i in range(total_minutes):
            res[i] = 1
        return res

    # Base weights for: [intro, explain, example, practice, quiz, recap]
    weights = [1, 3, 3, 4, 2, 2]
    total_weight = sum(weights)
    alloc = [max(1, int(total_minutes * w / total_weight)) for w in weights]
    diff = total_minutes - sum(alloc)

    # Priority order for distributing remaining minutes:
    # practice, example, explain, quiz, recap, intro
    priority = [3, 2, 1, 4, 5, 0]
    idx = 0
    while diff > 0:
        alloc[priority[idx % len(priority)]] += 1
        diff -= 1
        idx += 1
    while diff < 0:
        target = priority[idx % len(priority)]
        if alloc[target] > 1:
            alloc[target] -= 1
            diff += 1
        idx += 1
        if idx > 50:
            alloc[0] += diff
            break

    return alloc


