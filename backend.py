def generate_quiz(concept_ids: list[str]) -> Quiz:
    """
    Generates a 5-question quiz covering Python loops.
    Uses concept_ids 'range_bounds' and 'loop_body'.
    """
    # Filter or select questions based on requested concepts, ensuring all 5 questions are returned
    target_concepts = set(concept_ids) if concept_ids else {"range_bounds", "loop_body"}

    selected_questions: list[Question] = []
    # Guarantee 5 questions
    for q in MOCK_QUESTIONS.values():
        if q.concept_id in target_concepts or len(selected_questions) < 5:
            selected_questions.append(q)
        if len(selected_questions) == 5:
            break

    # If fewer than 5 matched, backfill from remaining
    if len(selected_questions) < 5:
        for q in MOCK_QUESTIONS.values():
            if q not in selected_questions:
                selected_questions.append(q)
            if len(selected_questions) == 5:
                break

    return Quiz(
        id="quiz_python_loops_01",
        topic="Python Loops: Bounds & Loop Execution",
        concept_ids=list(target_concepts),
        questions=selected_questions,
    )


def submit_answers(answers: list[Answer]) -> Result:
    """
    Evaluates submitted answers, scores each question, and identifies
    any weak concept IDs from incorrect answers.
    """
    score = 0
    total = len(MOCK_QUESTIONS)
    weak_concepts_set: set[str] = set()
    details: list[dict] = []

    answer_map = {ans.question_id: ans.selected_answer for ans in answers}

    for qid, q in MOCK_QUESTIONS.items():
        user_choice = answer_map.get(qid, "").strip()
        is_correct = user_choice == q.correct_answer.strip()

        if is_correct:
            score += 1
        else:
            weak_concepts_set.add(q.concept_id)

        details.append({
            "question_id": q.id,
            "concept_id": q.concept_id,
            "question": q.question,
            "selected_answer": user_choice,
            "correct_answer": q.correct_answer,
            "is_correct": is_correct,
            "explanation": q.explanation,
        })

    percentage = round((score / total) * 100, 1) if total > 0 else 0.0
    passed = percentage >= 60.0

    if score == total:
        feedback = "Perfect score! You have a crystal-clear understanding of loop bounds and loop execution."
    elif passed:
        feedback = "Great job! You passed the quiz. Review the highlighted concepts to refine your skills."
    else:
        feedback = "Keep practicing! Review the lesson material for the concepts you missed."

    return Result(
        score=score,
        total=total,
        percentage=percentage,
        passed=passed,
        feedback=feedback,
        weak_concepts=sorted(list(weak_concepts_set)),
        details=details,
    )
